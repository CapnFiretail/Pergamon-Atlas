// Generates PergamonAtlas.V1/styles/typography.css from the typography
// registry (PergamonAtlas.V1/scripts/design/typography.js).
//
//   node tools/build-typography.mjs          write the stylesheet
//   node tools/build-typography.mjs --check  exit 1 if it is out of date
//
// The stylesheet is committed (the Vercel build doesn't run this), and
// tests/design/typography.test.mjs fails when it is stale, so the registry
// stays the single source of truth. Never edit the output by hand.
import { createRequire } from 'node:module';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(ROOT, 'PergamonAtlas.V1/styles/typography.css');
const require = createRequire(import.meta.url);
const typo = require(path.join(ROOT, 'PergamonAtlas.V1/scripts/design/typography.js'));

const CSS_PROP = { family: 'font-family', size: 'font-size', weight: 'font-weight', leading: 'line-height', tracking: 'letter-spacing', transform: 'text-transform' };

export function build() {
  const { registry, PROPS, token, value } = typo;
  const errors = typo.validate(registry);
  if (errors.length) throw new Error('Typography registry is invalid:\n  ' + errors.join('\n  '));

  const lines = [
    '/* GENERATED by tools/build-typography.mjs from scripts/design/typography.js.',
    ' * Do not edit: change the registry and run `node tools/build-typography.mjs`.',
    ' *',
    ' * Semantic type roles: --type-<role>-<property> tokens on :root and one',
    ' * .pa-type-<role> class per role that applies them. Font families come from',
    ' * styles/theme.css (--font-display, --font-ui); the legacy serif is defined',
    ' * here so the current game header can be described. Text colour is not part',
    ' * of a role: it comes from the theme tokens. */',
    '',
    ':root {'
  ];
  for (const [, f] of Object.entries(registry.families)) {
    if (f.owner === 'styles/typography.css') lines.push(`  ${f.token}: ${f.stack.join(', ')};`);
  }
  for (const r of registry.roles) {
    lines.push(`  /* ${r.name} (${r.kind}${r.of ? ' of ' + r.of : ''}${r.status === 'legacy' ? ', legacy' : ''}) */`);
    for (const p of PROPS) if (value(r, p) !== 'inherit') lines.push(`  ${token(r.id, p)}: ${value(r, p)};`);
    if (r.numeric) lines.push(`  ${token(r.id, 'numeric')}: ${r.numeric};`);
  }
  lines.push('}', '');

  // Viewport steps, in registry order (narrower steps come later and win).
  for (const r of registry.roles) {
    for (const s of r.responsive || []) {
      if (s.type === 'media') lines.push(`@media ${s.query} { :root { ${token(r.id, 'size')}: ${s.size}; } }`);
    }
  }
  lines.push('');

  for (const r of registry.roles) {
    const decl = PROPS.map(p => `${CSS_PROP[p]}: ${value(r, p) === 'inherit' ? 'inherit' : `var(${token(r.id, p)})`};`);
    if (r.numeric) decl.push(`font-variant-numeric: var(${token(r.id, 'numeric')});`);
    lines.push(`.pa-type-${r.id} { ${decl.join(' ')} }`);
  }
  lines.push('');

  // Container steps apply to the role's class inside the named container.
  for (const r of registry.roles) {
    for (const s of r.responsive || []) {
      if (s.type === 'container') lines.push(`@container ${s.container} ${s.query} { .pa-type-${r.id} { ${token(r.id, 'size')}: ${s.size}; } }`);
    }
  }
  return lines.join('\n').replace(/\n{3,}/g, '\n\n').trimEnd() + '\n';
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const css = build();
  if (process.argv.includes('--check')) {
    let current = '';
    try { current = readFileSync(OUT, 'utf8').replace(/\r\n/g, '\n'); } catch (e) {}
    if (current !== css) { console.error('styles/typography.css is out of date: run node tools/build-typography.mjs'); process.exit(1); }
    console.log('styles/typography.css is up to date');
  } else {
    writeFileSync(OUT, css);
    console.log('wrote', path.relative(ROOT, OUT));
  }
}
