#!/usr/bin/env node
// Writes PergamonAtlas.V1/operation/scripts/auth/supabase-config.js for the
// deployment being built, from explicit per-environment variables.
//
// PREPARED, NOT YET ACTIVE. To activate (once the staging project exists):
//   vercel.json  "buildCommand": "node tools/write-supabase-config.mjs"
//   Vercel env   Production scope: PERGAMON_SUPABASE_URL / PERGAMON_SUPABASE_PUBLISHABLE_KEY = production values
//                Preview scope:    the same names = STAGING values
//                Development:      staging values (for `vercel dev` / local)
// Vercel sets VERCEL_ENV to production | preview | development.
//
// Safety rules (the build fails rather than ship a risky config):
//   - production requires both values;
//   - a non-production build may never use the production project;
//   - only public (publishable / anon) keys are accepted — a secret or
//     service-role key is refused so it can't reach browser code;
//   - a preview with no values gets an "unconfigured" file (auth disabled),
//     never the production fallback.
//
// Usage: node tools/write-supabase-config.mjs [--out <file>]
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

export const PRODUCTION_REF = 'rddijjezqrcjrnwskenb';

export function buildConfig(env) {
  const target = env.VERCEL_ENV || 'development';
  if (!['production', 'preview', 'development'].includes(target)) throw new Error(`Unknown VERCEL_ENV "${target}"`);
  const url = (env.PERGAMON_SUPABASE_URL || '').trim();
  const key = (env.PERGAMON_SUPABASE_PUBLISHABLE_KEY || '').trim();

  if (!url && !key) {
    if (target === 'production') throw new Error('Production build: PERGAMON_SUPABASE_URL and PERGAMON_SUPABASE_PUBLISHABLE_KEY are required');
    return { target, url: null, key: null };
  }
  if (!url || !key) throw new Error('Set both PERGAMON_SUPABASE_URL and PERGAMON_SUPABASE_PUBLISHABLE_KEY, or neither');

  const m = /^https:\/\/([a-z0-9]{20})\.supabase\.co$/.exec(url);
  if (!m) throw new Error('PERGAMON_SUPABASE_URL must look like https://<20-character ref>.supabase.co');
  const ref = m[1];
  if (target !== 'production' && ref === PRODUCTION_REF) {
    throw new Error(`A ${target} build must not use the production Supabase project`);
  }
  if (target === 'production' && ref !== PRODUCTION_REF) {
    throw new Error(`Production build points at project ${ref}, not the production project ${PRODUCTION_REF}`);
  }
  if (!isPublicKey(key)) throw new Error('PERGAMON_SUPABASE_PUBLISHABLE_KEY must be a publishable (sb_publishable_…) or anon key — never a secret or service-role key');
  return { target, url, key };
}

function isPublicKey(key) {
  if (/^sb_publishable_[A-Za-z0-9_-]{10,}$/.test(key)) return true;
  if (/^sb_secret_/.test(key)) return false;
  // Legacy JWT keys: accept only role "anon".
  const parts = key.split('.');
  if (parts.length !== 3) return false;
  try {
    const payload = JSON.parse(Buffer.from(parts[1].replace(/-/g, '+').replace(/_/g, '/'), 'base64').toString('utf8'));
    return payload.role === 'anon';
  } catch { return false; }
}

export function renderConfig({ target, url, key }) {
  return `// Generated by tools/write-supabase-config.mjs for the ${target} deployment. Do not edit.
//
// Public values only: the project URL and its publishable (anon) key are
// safe in browser code — Row Level Security is the security boundary.
// Never put a service_role or secret key here.

window.PERGAMON_ENV = ${JSON.stringify(target)};
window.PERGAMON_SUPABASE_URL = ${JSON.stringify(url)};
window.PERGAMON_SUPABASE_ANON_KEY = ${JSON.stringify(key)};
`;
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  const i = process.argv.indexOf('--out');
  const out = i > 0 ? process.argv[i + 1]
    : path.join(path.dirname(fileURLToPath(import.meta.url)), '..', 'PergamonAtlas.V1', 'operation', 'scripts', 'auth', 'supabase-config.js');
  try {
    const cfg = buildConfig(process.env);
    writeFileSync(out, renderConfig(cfg));
    console.log(`supabase-config.js: ${cfg.target} -> ${cfg.url || 'unconfigured (auth disabled)'}`);
  } catch (e) {
    console.error(`write-supabase-config: ${e.message}`);
    process.exit(1);
  }
}
